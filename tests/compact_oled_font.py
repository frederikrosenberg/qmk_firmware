"""Pack only the font glyphs used by OLED views, preserving their pixels.

The original font is an editing source; firmware includes only font.h.
Run with --check to verify committed generated files without writing.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
source = (ROOT / "user/font_source.h").read_text()
original = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})", source)]
assert len(original) == 256 * 6
oled = (ROOT / "user/oled.c").read_text()
used = sorted({int(v, 16) for v in re.findall(r"OLED_GLYPH_([0-9A-F]{2})", oled)})
assert used and all(v >= 128 for v in used)
glyphs = [original[i * 6:(i + 1) * 6] for i in range(32, 127)]
mapping = {}
for old in used:
    pixels = original[old * 6:(old + 1) * 6]
    if pixels not in glyphs:
        glyphs.append(pixels)
    mapping[old] = 32 + glyphs.index(pixels)
    assert glyphs[mapping[old] - 32] == pixels
end = 32 + len(glyphs) - 1
assert end <= 255
font = source.split("static const", 1)[0]
font += "// Generated by tests/compact_oled_font.py; edit font_source.h.\n"
font += "static const unsigned char PROGMEM font[] = {\n"
font += "".join("    " + ", ".join(f"0x{v:02X}" for v in glyph) + ",\n" for glyph in glyphs)
font += "};\n"
defines = "// Generated by tests/compact_oled_font.py.\n#pragma once\n\n"
defines += f"#define OLED_COMPACT_FONT_END {end}\n"
defines += "".join(f"#define OLED_GLYPH_{old:02X} 0x{new:02X}\n" for old, new in mapping.items())
for name, content in [("font.h", font), ("oled_glyphs.h", defines)]:
    path = ROOT / "user" / name
    if args.check:
        assert path.read_text() == content, f"Regenerate {name}"
    else:
        path.write_text(content, encoding="utf-8")
print(f"OLED font: {len(glyphs) * 6} bytes, {len(mapping)} custom glyphs verified; "
      f"{len(original) - len(glyphs) * 6} bytes removed")
